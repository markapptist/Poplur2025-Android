private val Gold = Color(0xFFFFD700)
private val Pink = Color(0xFFFF4DB8)
private val PageBg = Color(0xFF0F0F1A)
private val CardBg = Color(0xFF1C1C2B)

private fun gameColor(hex: String): Color = try {
    Color(android.graphics.Color.parseColor(hex))
} catch (_: Exception) { Color(0xFF2A2A44) }

// MARK: config → the matching Compose game

@Composable
fun PoplurGamePlayScreen(config: PoplurGameConfig, onDismiss: () -> Unit) {
    when (config.game) {
        PoplurGameType.SideScroller -> PopRunnerGame(config, onDismiss)
        PoplurGameType.ArcadeShooter -> StellaBlastGame(config, onDismiss)
        PoplurGameType.ActionAdventure -> ZylaQuestGame(config, onDismiss)
        PoplurGameType.Sports -> RexHoopsGame(config, onDismiss)
    }
}

// MARK: Game Maker

@Composable
fun GameMakerScreen(onDismiss: () -> Unit) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    remember { PoplurSavedGamesStore.init(context) }

    var prompt by remember { mutableStateOf("") }
    var generating by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf<PoplurGameConfig?>(null) }
    var playing by remember { mutableStateOf<PoplurGameConfig?>(null) }
    var placementNote by remember { mutableStateOf<String?>(null) }

    // Playing a game takes over the whole screen.
    playing?.let { cfg ->
        PoplurGamePlayScreen(cfg) { playing = null }
        return
    }

    Box(Modifier.fillMaxSize().background(PageBg)) {
        Column(
            Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(20.dp),
            verticalArrangement = Arrangement.spacedBy(18.dp)
        ) {
            // Header
            Row(verticalAlignment = Alignment.CenterVertically) {
                Text("Game Maker", color = Color.White, fontSize = 26.sp, fontWeight = FontWeight.Black)
                Spacer(Modifier.weight(1f))
                IconButton(onClick = onDismiss) {
                    Icon(Icons.Filled.Close, "Close", tint = Color.White)
                }
            }

            // Maker card
            Column(
                Modifier.fillMaxWidth()
                    .background(CardBg, RoundedCornerShape(20.dp))
                    .padding(18.dp),
                verticalArrangement = Arrangement.spacedBy(12.dp)
            ) {
                Text("Describe your game", color = Color.White, fontSize = 19.sp, fontWeight = FontWeight.Black)
                Text("The AI picks the type, theme, colors and mechanics from your idea.",
                    color = Color.White.copy(alpha = 0.55f), fontSize = 13.sp)

                OutlinedTextField(
                    value = prompt,
                    onValueChange = { prompt = it.take(240) },
                    placeholder = { Text("e.g. a neon jungle runner with double jumps", color = Color.White.copy(alpha = 0.3f)) },
                    minLines = 3,
                    colors = OutlinedTextFieldDefaults.colors(
                        focusedBorderColor = Gold,
                        unfocusedBorderColor = Color.White.copy(alpha = 0.2f),
                        focusedContainerColor = Color.Black.copy(alpha = 0.3f),
                        unfocusedContainerColor = Color.Black.copy(alpha = 0.3f),
                        cursorColor = Gold,
                        focusedTextColor = Color.White,
                        unfocusedTextColor = Color.White
                    ),
                    shape = RoundedCornerShape(12.dp),
                    modifier = Modifier.fillMaxWidth()
                )

                Button(
                    onClick = {
                        generating = true
                        scope.launch {
                            generated = PoplurGameService.generateUserGame(prompt)
                            generating = false
                        }
                    },
                    enabled = !generating,
                    modifier = Modifier.fillMaxWidth().height(52.dp),
                    shape = RoundedCornerShape(14.dp),
                    colors = ButtonDefaults.buttonColors(containerColor = Gold, contentColor = Color.Black)
                ) {
                    if (generating) {
                        CircularProgressIndicator(color = Color.Black, modifier = Modifier.size(20.dp), strokeWidth = 2.dp)
                        Spacer(Modifier.width(8.dp))
                        Text("Generating…", fontWeight = FontWeight.Black)
                    } else {
                        Icon(Icons.Filled.AutoAwesome, null)
                        Spacer(Modifier.width(8.dp))
                        Text("Generate Game", fontWeight = FontWeight.Black)
                    }
                }
            }

            // Preview of generated config
            generated?.let { cfg ->
                Column(
                    Modifier.fillMaxWidth().background(CardBg, RoundedCornerShape(20.dp)).padding(14.dp),
                    verticalArrangement = Arrangement.spacedBy(12.dp)
                ) {
                    Box(
                        Modifier.fillMaxWidth().height(90.dp)
                            .background(
                                Brush.linearGradient(listOf(gameColor(cfg.skyColor), gameColor(cfg.accentColor))),
                                RoundedCornerShape(14.dp)
                            ).padding(12.dp),
                        contentAlignment = Alignment.BottomStart
                    ) {
                        Column {
                            Text(cfg.gameName, color = Color.White, fontSize = 20.sp, fontWeight = FontWeight.Black)
                            Text("${cfg.game.displayName} · ${cfg.theme} · ${cfg.difficulty}",
                                color = Color.White.copy(alpha = 0.85f), fontSize = 12.sp, fontWeight = FontWeight.Bold)
                        }
                    }
                    Text("Special: ${cfg.specialMechanic}", color = Color.White.copy(alpha = 0.65f), fontSize = 13.sp)
                    Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                        Button(
                            onClick = { PoplurSavedGamesStore.add(cfg); generated = null; prompt = "" },
                            modifier = Modifier.weight(1f).height(46.dp),
                            shape = RoundedCornerShape(12.dp),
                            colors = ButtonDefaults.buttonColors(containerColor = Pink, contentColor = Color.Black)
                        ) {
                            Icon(Icons.Filled.Add, null); Spacer(Modifier.width(6.dp))
                            Text("Save to My Games", fontWeight = FontWeight.Black, fontSize = 14.sp)
                        }
                        IconButton(
                            onClick = {
                                generating = true
                                scope.launch { generated = PoplurGameService.generateUserGame(prompt); generating = false }
                            },
                            modifier = Modifier.size(46.dp).background(Color.White.copy(alpha = 0.1f), RoundedCornerShape(12.dp))
                        ) { Icon(Icons.Filled.Refresh, "Regenerate", tint = Color.White) }
                    }
                }
            }

            // My Games
            Text("My Games", color = Color.White, fontSize = 20.sp, fontWeight = FontWeight.Black)
            if (PoplurSavedGamesStore.games.isEmpty()) {
                Text("Games you make will show up here.", color = Color.White.copy(alpha = 0.4f), fontSize = 14.sp)
            } else {
                PoplurSavedGamesStore.games.forEach { g ->
                    SavedGameRow(
                        game = g,
                        onPlay = { playing = g.config },
                        onPlace = {
                            PoplurSavedGamesStore.pendingPlacement = g
                            placementNote = "Open the Map and tap where you want \"${g.config.gameName}\" to appear."
                        },
                        onUnplace = { PoplurSavedGamesStore.unplace(g) },
                        onDelete = { PoplurSavedGamesStore.remove(g) }
                    )
                }
            }

            placementNote?.let {
                Text(it, color = Gold, fontSize = 13.sp, fontWeight = FontWeight.Bold)
            }
            Spacer(Modifier.height(24.dp))
        }
    }
}

@Composable
private fun SavedGameRow(
    game: PoplurSavedGame,
    onPlay: () -> Unit,
    onPlace: () -> Unit,
    onUnplace: () -> Unit,
    onDelete: () -> Unit
) {
    Row(
        Modifier.fillMaxWidth().background(CardBg, RoundedCornerShape(16.dp)).padding(10.dp),
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.spacedBy(10.dp)
    ) {
        Box(
            Modifier.size(44.dp).background(
                Brush.verticalGradient(listOf(gameColor(game.config.skyColor), gameColor(game.config.accentColor))),
                RoundedCornerShape(10.dp)
            )
        )
        Column(Modifier.weight(1f)) {
            Text(game.config.gameName, color = Color.White, fontSize = 16.sp, fontWeight = FontWeight.Bold, maxLines = 1)
            Text(
                game.config.game.displayName + if (game.isPlaced) " · On map" else "",
                color = if (game.isPlaced) Gold else Color.White.copy(alpha = 0.5f),
                fontSize = 12.sp, fontWeight = FontWeight.SemiBold
            )
        }
        IconButton(onClick = onPlay, modifier = Modifier.size(38.dp).background(Gold, CircleShape)) {
            Icon(Icons.Filled.PlayArrow, "Play", tint = Color.Black)
        }
        IconButton(
            onClick = if (game.isPlaced) onUnplace else onPlace,
            modifier = Modifier.size(38.dp).background(Color.White.copy(alpha = 0.08f), CircleShape)
        ) {
            Icon(Icons.Filled.LocationOn, "Place", tint = if (game.isPlaced) Gold else Color.White)
        }
        IconButton(
            onClick = onDelete,
            modifier = Modifier.size(38.dp).background(Color.White.copy(alpha = 0.08f), CircleShape)
        ) {
            Icon(Icons.Filled.Delete, "Delete", tint = Color.White.copy(alpha = 0.7f))
        }
    }
}
